-- 用途：看板筛选器（组织+月份）的数据源；店面→组织映射
-- ============================================================

-- dim_组织：组织表，保留所有组织（不可用=改名不是不用），排除非运营（供应链公司、长沙顶鼎房地产咨询服务有限公司）
CREATE OR REPLACE VIEW dim_组织 AS
SELECT
    序号,
    组织机构,
    全房通名称                AS 店面,
    部门属性,
    使用状态,
    内部收入使用组织机构,
    -- 组织表中没有的组织需要在看板/核查中提示，这里先标记
    CASE
        WHEN 组织机构 IN (
            '总公司新毛坯三','装修子公司','业务子公司','高奢精空子公司',
            '焕新子公司','装修代售店','雨花分公司','精装托管二店',
            '老店面（新毛坯2）','出租子公司','家服','精装托管三店',
            '家装业务部'
        ) THEN 1 ELSE 0
    END                        AS 是否运营组织
FROM 组织
WHERE 组织机构 NOT IN ('供应链公司', '长沙顶鼎房地产咨询服务有限公司')
ORDER BY 序号::int;

-- dim_月份：从 2025-01 起
CREATE OR REPLACE VIEW dim_月份 AS
SELECT DISTINCT
    to_char(实收付日期, 'YYYY-MM') AS 月份
FROM 数据汇总表
WHERE 实收付日期 >= '2025-01-01'
UNION
SELECT DISTINCT 月份 FROM 店面出租率
WHERE 月份 >= '2025-01'
ORDER BY 月份;

-- dim_店面组织映射：店面→组织机构
CREATE OR REPLACE VIEW dim_店面组织映射 AS
SELECT DISTINCT
    全房通名称 AS 店面,
    组织机构
FROM 组织
WHERE 全房通名称 IS NOT NULL AND 全房通名称 != '';
